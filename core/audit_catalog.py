def audit_item_name(item_id: str) -> str:
    normalized = item_id.strip().upper().replace("_", "-")
    return AUDIT_ITEM_NAMES.get(normalized, normalized)


def audit_group_name(item_id: str) -> str:
    normalized = item_id.strip().upper().replace("_", "-")
    prefix = normalized.split("-", 1)[0]
    return AUDIT_GROUP_NAMES.get(prefix, prefix)


def audit_item_enabled(item_id: str) -> bool:
    normalized = item_id.strip().upper().replace("_", "-")
    return normalized not in DISABLED_ITEMS
